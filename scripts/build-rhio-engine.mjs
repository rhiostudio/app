// Builds the RHIO 3D character engine from lib/rhio3d/src into:
//   lib/rhio3d/data.js            presets / wardrobe / powers (small, loads with the app)
//   lib/rhio3d/content.js         docs, whitepaper, roadmap text
//   lib/rhio3d/engine.js          3D engine (three is passed in); loaded lazily by app/avatar.tsx
//   standalone/rhio-studio.html   single-file studio page (loads three from jsDelivr); only when its page
//                                 source lib/rhio3d/src/page.html is present (it is not kept in the repository)
// Usage: node scripts/build-rhio-engine.mjs
import { existsSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const src = f => readFileSync(join(root, 'lib/rhio3d/src', f), 'utf8');
const engineFiles = ['e1-core.js', 'e2-human.js', 'e3-companion.js', 'e4-motion.js', 'e5-stage.js'];
const dataFiles = ['data.js', 'skills.js', 'content.js']; // standalone page only
// each source is an IIFE `(function (G) { ... })(window);` — rebind it to a local namespace object
const rebind = code => code.replace(/\}\)\(window\);\s*$/, '})(G);');

const header = `// @ts-nocheck
/* GENERATED by scripts/build-rhio-engine.mjs from lib/rhio3d/src — edit the sources, then rebuild. */`;
// Split so the first page load never pulls the 3D code: data (presets, wardrobe) is small and used
// everywhere, content (docs, whitepaper) is text, and the engine loads only when a 3D view is shown.
writeFileSync(join(root, 'lib/rhio3d/data.js'), `${header}
/** Installs presets, wardrobe options, motion groups and powers on G.RHIO. Safe on the server (no three.js). */
export function installData(G) {
${rebind(src('data.js'))}
}
export const RHIO_DATA = (() => { const G = { RHIO: {} }; installData(G); return G.RHIO; })();
`);
writeFileSync(join(root, 'lib/rhio3d/content.js'), `${header}
/** Docs, whitepaper and roadmap text. */
export const CONTENT = (() => { const G = { RHIO: {} };
${rebind(src('content.js'))}
return G.RHIO.CONTENT; })();
`);
writeFileSync(join(root, 'lib/rhio3d/engine.js'), `${header}
import { installData } from './data.js';
function installEngine(G) {
${engineFiles.map(f => rebind(src(f))).join('\n')}
}
/** Creates the browser engine (Stage, renderThumb, builders). Call only in the browser with the three namespace. */
export function createEngine(THREE) {
  const G = { THREE, RHIO: {} };
  installData(G); installEngine(G);
  return G.RHIO;
}
`);

if (existsSync(join(root, 'lib/rhio3d/src/page.html'))) {
  const page = src('page.html');
  const all = [...engineFiles, ...dataFiles, 'app.js'].map(src).join('\n');
  mkdirSync(join(root, 'standalone'), { recursive: true });
  writeFileSync(join(root, 'standalone/rhio-studio.html'), `<!doctype html>
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1,viewport-fit=cover"></head><body>
${page}
<script src="https://cdn.jsdelivr.net/npm/three@0.158.0/build/three.min.js"></script>
<script>
${all}
</script>
</body></html>
`);
  console.log('Built lib/rhio3d/{data,content,engine}.js and standalone/rhio-studio.html');
} else console.log('Built lib/rhio3d/{data,content,engine}.js (no page.html: standalone page skipped)');
